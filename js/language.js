const langButtons = document.querySelectorAll('.lang-btn');
const i18nNodes = document.querySelectorAll('[data-i18n]');
const i18nPlaceholderNodes = document.querySelectorAll('[data-i18n-placeholder]');

function applyLanguage(lang) {
  const selected = translations[lang] || translations.en;

  html.setAttribute('lang', lang);
  html.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  html.setAttribute('data-lang', lang);

  i18nNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (selected[key]) {
      node.innerHTML = selected[key];
    }
  });

  i18nPlaceholderNodes.forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (selected[key]) {
      node.placeholder = selected[key];
      const label = node.getAttribute('aria-label');
      if (label) {
        node.setAttribute('aria-label', selected[key]);
      }
    }
  });

  langButtons.forEach((button) => {
    const isActive = button.dataset.lang === lang;
    button.classList.toggle('is-active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });
}

function initLanguage() {
  const savedLang = localStorage.getItem('portfolio-lang') || 'en';
  applyLanguage(savedLang);

  langButtons.forEach((button) => {
    button.addEventListener('click', () => {
      const nextLang = button.dataset.lang;
      localStorage.setItem('portfolio-lang', nextLang);
      applyLanguage(nextLang);
    });
  });
}

initLanguage();
